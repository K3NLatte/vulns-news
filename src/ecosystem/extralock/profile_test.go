func TestLimits(t *testing.T) {
	for _, kind := range []string{"file", "total", "entries", "depth", "components"} {
		t.Run(kind, func(t *testing.T) {
			root := t.TempDir()
			lim := defaultLimits
			switch kind {
			case "file":
				lim.fileBytes = 16
				put(t, root, "pubspec.lock", pubFixture)
			case "total":
				lim.totalBytes = len(pubFixture) + 1
				put(t, root, "a/pubspec.lock", pubFixture)
				put(t, root, "b/pubspec.lock", pubFixture)
			case "entries":
				lim.entries = 1
				put(t, root, "a", "")
				put(t, root, "b", "")
			case "depth":
				lim.depth = 1
				put(t, root, "a/b/pubspec.lock", pubFixture)
			case "components":
				lim.components = 1
				put(t, root, "pubspec.lock", pubFixture)
			}
			f, err := profile(root, lim)
			if err == nil || !strings.Contains(err.Error(), "limit exceeded") || !reflect.DeepEqual(f, Fragment{}) {
				t.Fatalf("%+v, %v", f, err)
			}
		})
	}
	for _, tc := range []struct{ name, data string }{
		{"deno.lock", strings.Repeat("[", 66) + "0" + strings.Repeat("]", 66)},
		{"pubspec.lock", "x: " + strings.Repeat("[", 66) + "0" + strings.Repeat("]", 66)},
		{"packages.config", strings.Repeat("<x>", 66) + strings.Repeat("</x>", 66)},
	} {
		t.Run(tc.name, func(t *testing.T) {
			root := t.TempDir()
			put(t, root, tc.name, tc.data)
			_, err := Profile(root)
			if err == nil || !strings.Contains(err.Error(), "nesting limit") {
				t.Fatalf("%v", err)
			}
		})
	}
}
func TestSymlinksAndRoot(t *testing.T) {
	root := t.TempDir()
	outside := t.TempDir()
	put(t, outside, "pubspec.lock", "malformed: [")
	put(t, root, "actual/pubspec.lock", pubFixture)
	for _, link := range []struct{ target, name string }{{filepath.Join(outside, "pubspec.lock"), "pubspec.lock"}, {outside, "external"}, {filepath.Join(root, "actual"), "internal"}, {root, "loop"}, {filepath.Join(outside, "missing"), "broken"}} {
		if err := os.Symlink(link.target, filepath.Join(root, link.name)); err != nil {
			t.Skipf("symlink creation unavailable: %v", err)
		}
	}
	f, err := Profile(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(f.Components) != 3 {
		t.Fatalf("symlinks followed: %+v", f)
	}
	if _, err := Profile(filepath.Join(root, "internal")); err == nil {
		t.Fatal("symlink root accepted")
	}
	for _, bad := range []string{"", filepath.Join(root, "missing"), filepath.Join(root, "actual/pubspec.lock")} {
		if _, err := Profile(bad); err == nil {
			t.Fatalf("bad root accepted: %q", bad)
		}
	}
}
