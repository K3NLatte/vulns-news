func put(t *testing.T, root, name, content string) {
	t.Helper()
	file := filepath.Join(root, filepath.FromSlash(name))
	if err := os.MkdirAll(filepath.Dir(file), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(file, []byte(content), 0600); err != nil {
		t.Fatal(err)
	}
}
func TestRealisticInventory(t *testing.T) {
	root := t.TempDir()
	fixtures := map[string]string{"dart/pubspec.lock": pubFixture, "deno/deno.lock": denoFixture, "dotnet/packages.config": configFixture, "dotnet/obj/project.assets.json": assetsFixture, "r/renv.lock": renvFixture}
	for file, data := range fixtures {
		put(t, root, file, data)
	}
	f, err := Profile(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(f.Components) != 12 {
		t.Fatalf("got %d components: %+v", len(f.Components), f.Components)
	}
	wantEcos := []string{"CRAN", "JSR", "NuGet", "Pub", "npm"}
	var ecos []string
	for _, e := range f.Ecosystems {
		ecos = append(ecos, e.Name)
	}
	if !reflect.DeepEqual(ecos, wantEcos) {
		t.Fatalf("ecosystems: %v", ecos)
	}
	byName := map[string][]domain.Component{}
	ids := map[string]bool{}
	for _, c := range f.Components {
		if c.ID == "" || ids[c.ID] {
			t.Fatalf("bad ID: %+v", c)
		}
		ids[c.ID] = true
		if _, ok := fixtures[c.SourcePath]; !ok {
			t.Fatalf("invalid source path: %+v", c)
		}
		if strings.Contains(c.PURL, "@") || strings.Contains(c.PURL, c.Version) {
			t.Fatalf("versioned PURL: %+v", c)
		}
		byName[c.Name] = append(byName[c.Name], c)
	}
	for name, want := range map[string]string{"@scope/tool": "pkg:npm/%40scope/tool", "@std/path": "pkg:jsr/%40std/path", "MASS": "pkg:cran/MASS", "newtonsoft.json": "pkg:nuget/newtonsoft.json", "collection": "pkg:pub/collection"} {
		if len(byName[name]) == 0 || byName[name][0].PURL != want {
			t.Fatalf("%s: %+v", name, byName[name])
		}
	}
	if byName["@scope/tool"][0].Namespace != "@scope" || byName["@std/path"][0].Namespace != "@std" {
		t.Fatal("namespace lost")
	}
	if byName["my_tool"][0].Version != "1.2.3" {
		t.Fatal("peer context became version")
	}
	if len(byName["newtonsoft.json"]) != 2 {
		t.Fatal("source provenance was deduplicated")
	}
	if !byName["collection"][0].Direct || byName["test"][0].Scope != "development" || byName["async"][0].Direct {
		t.Fatal("pub dependency classification")
	}
	for _, c := range byName["newtonsoft.json"] {
		if c.Direct {
			t.Fatal("NuGet directness is not known")
		}
	}
	for _, e := range f.Ecosystems {
		if e.Name == "NuGet" && (!reflect.DeepEqual(e.Manifests, []string{"dotnet/packages.config"}) || !reflect.DeepEqual(e.Lockfiles, []string{"dotnet/obj/project.assets.json"})) {
			t.Fatalf("NuGet usage: %+v", e)
		}
	}
	if !strings.Contains(strings.Join(f.Warnings, "\n"), "no OSV") {
		t.Fatal("missing CRAN coverage caveat")
	}
	again, err := Profile(root)
	if err != nil || !reflect.DeepEqual(f, again) {
		t.Fatalf("non-deterministic profile: %v", err)
	}
	other := t.TempDir()
	for file, data := range fixtures {
		put(t, other, file, data)
	}
	relocated, err := Profile(other)
	if err != nil || !reflect.DeepEqual(f, relocated) {
		t.Fatalf("absolute root affects inventory: %v", err)
	}
}

func TestDenoVersions(t *testing.T) {
	npm := `{"@a/b@1.2.3":{"integrity":"sha512-abc=="}}`
	for _, tc := range []struct{ version, body string }{
		{"2", `"npm":{"specifiers":{"@a/b@^1":"@a/b@1.2.3"},"packages":` + npm + `}`},
		{"3", `"packages":{"specifiers":{"npm:@a/b@^1":"npm:@a/b@1.2.3"},"npm":` + npm + `}`},
		{"4", `"npm":` + npm}, {"5", `"npm":` + npm},
	} {
		t.Run(tc.version, func(t *testing.T) {
			root := t.TempDir()
			put(t, root, "deno.lock", `{"version":"`+tc.version+`",`+tc.body+`}`)
			f, err := Profile(root)
			if err != nil {
				t.Fatal(err)
			}
			if len(f.Components) != 1 || f.Components[0].Name != "@a/b" {
				t.Fatalf("%+v", f)
			}
		})
	}
}

